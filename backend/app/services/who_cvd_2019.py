def risk_category(value: int) -> str:
    if value < 5:
        return "<5%"
    if value < 10:
        return "5% to <10%"
    if value < 20:
        return "10% to <20%"
    if value < 30:
        return "20% to <30%"
    return "≥30%"

def _age_band(age: int) -> str:
    if not 40 <= age <= 74:
        raise ValueError("WHO South Asia charts apply to ages 40 through 74")
    lower = age - (age % 5)
    return f"{lower}-{lower + 4}"

def _sbp_band(sbp: float) -> str:
    if sbp < 120: return "<120"
    if sbp < 140: return "120-139"
    if sbp < 160: return "140-159"
    if sbp < 180: return "160-179"
    return "≥180"

def _cholesterol_band(mmol_l: float) -> int:
    if mmol_l <= 0:
        raise ValueError("Total cholesterol must be a positive measurement")
    if mmol_l < 4: return 0
    if mmol_l < 5: return 1
    if mmol_l < 6: return 2
    if mmol_l < 7: return 3
    return 4

def lookup_who_south_asia(age: int, sex: str, smoking: bool, diabetes: bool, sbp_mmhg: float, cholesterol_mmol_l: float) -> dict:
    """Return the published chart cell and risk band for eligible, complete inputs."""
    sex = sex.strip().lower()
    if sex not in ("male", "female"):
        raise ValueError("WHO chart requires sex recorded as male or female")
    if not isinstance(smoking, bool) or not isinstance(diabetes, bool):
        raise ValueError("Smoking and diabetes status must be verified yes/no values")
    if sbp_mmhg <= 0:
        raise ValueError("Systolic blood pressure must be a positive measurement")
    age_label = _age_band(age)
    sbp_label = _sbp_band(sbp_mmhg)
    chol_index = _cholesterol_band(cholesterol_mmol_l)
    row = next((r for r in _CHART_ROWS if r[0] == age_label and r[1] == sbp_label), None)
    if row is None:
        raise ValueError("No WHO chart cell exists for these inputs")
    col = SEX_SMOKING_COLUMNS.index((sex, smoking))
    published_percent = (row[3] if diabetes else row[2])[col * 5 + chol_index]
    return {
        "risk_category": risk_category(published_percent),
        "chart_value_percent": published_percent,
        "age_band": age_label,
        "systolic_blood_pressure_band": sbp_label,
        "cholesterol_band": CHOLESTEROL_BANDS[chol_index],
        "sex": sex,
        "current_smoker": smoking,
        "diabetes": diabetes,
    }
